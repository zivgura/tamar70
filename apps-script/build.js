// Bundles src/ (and the parts of shared/ and zod it uses) into dist/Code.js for clasp.
// Apps Script only runs functions *declared* at the top level of a file, so the footer
// declares each entry point and forwards it into the bundle.
import { copyFileSync, mkdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const GLOBAL = 'Tamar70'

// Called by Google (doGet, doPost) or run by hand from the editor (setup, rotateFamilyCode).
export const ENTRY_POINTS = ['doGet', 'doPost', 'setup', 'rotateFamilyCode']

export async function buildBundle(outdir = join(here, 'dist')) {
  rmSync(outdir, { recursive: true, force: true })
  mkdirSync(outdir, { recursive: true })

  await build({
    entryPoints: [join(here, 'src/main.js')],
    outfile: join(outdir, 'Code.js'),
    bundle: true,
    format: 'iife',
    globalName: GLOBAL,
    platform: 'neutral',
    mainFields: ['module', 'main'],
    target: 'es2019',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: '// Generated by apps-script/build.js. Do not edit here: edit apps-script/src.' },
    footer: {
      js: ENTRY_POINTS.map(
        (name) => `function ${name}(...args) { return ${GLOBAL}.${name}(...args) }`,
      ).join('\n'),
    },
    logLevel: 'warning',
  })

  copyFileSync(join(here, 'appsscript.json'), join(outdir, 'appsscript.json'))
  return join(outdir, 'Code.js')
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await buildBundle()
  console.log(`Built dist/Code.js (entry points: ${ENTRY_POINTS.join(', ')})`)
}
